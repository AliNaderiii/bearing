#!/usr/bin/env python
"""Build the LaTeX tables and figures of the MSSP manuscript directly from the result files
(no hand-copied numbers).

    python scripts/paper_assets.py                        # reads results/main_tuned + results/main_benchmark
    python scripts/paper_assets.py --exps smoke_mssp      # any experiments

Outputs (inside the project, nothing is written elsewhere): results/_paper_assets/
    tab_main_white_abs.tex   clean / 0 / -6 / -10 dB, absolute SNR, white noise (Table 'main')
    tab_relative.tex         relative SNR, white noise
    tab_noise_types.tex      white / pink / impulsive at -6 dB absolute SNR
    tab_complexity.tex       parameters, MACs, latency
    Figure_5_snr_curves.pdf  accuracy vs SNR per dataset group
    Figure_6_impulsive.pdf   impulsive vs white at -6 dB
    summary.csv              every number used above
Copy the folder content into paper_mssp/tables and paper_mssp/figures.
"""
from __future__ import annotations

import argparse
import os
import re

import numpy as np
import pandas as pd

import _bootstrap  # noqa: F401
from _bootstrap import ROOT
from phyq.analysis.tables import collect

MODELS = [  # (result tag, label in the paper) -- order of the rows
    ("phyq_nomed", "PhyQ-TransNet"),
    ("phyq_nomed_noquad", "Linear twin"),
    ("cnn_transformer", "CNN--Transformer"),
    ("drsn", "DRSN-CW"),
    ("qcnn", "QCNN"),
    ("wdcnn", "WDCNN"),
    ("stats_mlp", "Statistics MLP"),
    ("classbd", "ClassBD"),
    ("kurtogram_ses", "Fast Kurtogram + SES"),
]


def group_of(dataset: str, variant: str):
    if dataset == "cwru" and re.fullmatch(r"within_\dHP", variant):
        return "CWRU"
    if dataset == "pu" and re.fullmatch(r"fold\d", variant):
        return "PU 5-fold"
    if dataset == "pu" and variant == "art2real":
        return "PU art2real"
    if dataset in ("ims", "nrel", "sdust", "synthetic"):
        return dataset.upper()
    return None


def cell_values(df, noise, mode, snr, metric="acc"):
    """mean over seeds of (mean over tasks of the group) -> DataFrame [group, model, mean, std, n_seeds]."""
    if snr is None:
        d = df[df.noise == "clean"]
    else:
        d = df[(df.noise == noise) & (df["mode"] == mode) & (df.snr == float(snr))]
    if d.empty:
        return pd.DataFrame(columns=["group", "model", "mean", "std", "n"])
    per_seed = d.groupby(["group", "model", "seed"])[metric].mean().reset_index()
    return per_seed.groupby(["group", "model"])[metric].agg(["mean", "std", "count"]).reset_index() \
        .rename(columns={"count": "n"})


def fmt(v, bold):
    s = f"{v:.1f}"
    return f"\\textbf{{{s}}}" if bold else s


def table(df, groups, conds, caption_hint):
    """rows = models, columns = groups, each cell 'c1 / c2 / ...' over the conditions."""
    vals = {}
    for c in conds:
        cv = cell_values(df, *c)
        for _, r in cv.iterrows():
            vals[(r.group, r.model, c)] = r["mean"]
    labels = dict(MODELS)
    present = [m for m, _ in MODELS if any(k[1] == m for k in vals)]
    lines = [f"% generated by scripts/paper_assets.py -- {caption_hint}",
             "\\begin{tabular}{l" + "l" * len(groups) + "}", "\\toprule",
             "Model & " + " & ".join(groups) + " \\\\", "\\midrule"]
    for m in present:
        cells = []
        for g in groups:
            parts = []
            for c in conds:
                v = vals.get((g, m, c))
                if v is None or np.isnan(v):
                    parts.append("--")
                    continue
                best = max(vals.get((g, mm, c), -1) for mm, _ in MODELS)
                parts.append(fmt(v, abs(v - best) < 1e-9))
            cells.append(" / ".join(parts))
        lines.append(labels[m] + " & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exps", nargs="+", default=["main_tuned", "main_benchmark"])
    ap.add_argument("--out", default=os.path.join(ROOT, "results", "_paper_assets"))
    a = ap.parse_args()
    res = os.path.join(ROOT, "results")
    parts = []
    for rank, e in enumerate(a.exps):
        d = collect(res, e)
        if not d.empty:
            d = d.copy(); d["_exp_rank"] = rank
            parts.append(d)
    if not parts:
        raise SystemExit("no results found")
    df = pd.concat(parts, ignore_index=True)
    df = df[df["eval"] == "test"].copy()
    df["group"] = [group_of(d, v) for d, v in zip(df.dataset, df.variant)]
    df = df[df.group.notna() & df.model.isin([m for m, _ in MODELS])]
    # never pool experiments: for every (group, model) keep only the FIRST experiment of --exps that
    # contains it (e.g. tuned CWRU/IMS/NREL/SDUST runs from main_tuned, PU runs from main_benchmark);
    # otherwise untuned main_benchmark runs would be averaged with the tuned ones.
    first = df.groupby(["group", "model"])["_exp_rank"].transform("min")
    df = df[df["_exp_rank"] == first].drop(columns="_exp_rank")
    order = ["CWRU", "IMS", "NREL", "SDUST", "PU 5-fold", "PU art2real", "SYNTHETIC"]
    groups = [g for g in order if g in set(df.group)]
    os.makedirs(a.out, exist_ok=True)

    snr_conds = [(None, None, None), ("white", "absolute", 0), ("white", "absolute", -6), ("white", "absolute", -10)]
    open(os.path.join(a.out, "tab_main_white_abs.tex"), "w").write(
        table(df, groups, snr_conds, "accuracy %, white noise, absolute SNR: clean / 0 / -6 / -10 dB"))
    rel = [("white", "relative", 0), ("white", "relative", -6), ("white", "relative", -10)]
    open(os.path.join(a.out, "tab_relative.tex"), "w").write(
        table(df, groups, rel, "accuracy %, white noise, relative SNR: 0 / -6 / -10 dB"))
    types = [("white", "absolute", -6), ("pink", "absolute", -6), ("impulsive", "absolute", -6)]
    open(os.path.join(a.out, "tab_noise_types.tex"), "w").write(
        table(df, groups, types, "accuracy %, -6 dB absolute SNR: white / pink / impulsive"))

    # complexity (per group: channels/length differ)
    labels = dict(MODELS)
    cx = df.groupby(["group", "model"])[["params", "macs", "latency_ms"]].mean().reset_index()
    lines = ["% generated by scripts/paper_assets.py", "\\begin{tabular}{llrrr}", "\\toprule",
             "Dataset & Model & Params (M) & MACs (M) & Latency (ms) \\\\", "\\midrule"]
    for g in groups:
        for m, _ in MODELS:
            r = cx[(cx.group == g) & (cx.model == m)]
            if r.empty:
                continue
            r = r.iloc[0]
            macs = "--" if pd.isna(r.macs) else f"{r.macs / 1e6:.1f}"
            lat = "--" if pd.isna(r.latency_ms) else f"{r.latency_ms:.2f}"
            lines.append(f"{g} & {labels[m]} & {r.params / 1e6:.2f} & {macs} & {lat} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    open(os.path.join(a.out, "tab_complexity.tex"), "w").write("\n".join(lines))

    # summary of every number
    allc = []
    for kind in ("white", "pink", "impulsive"):
        for mode in ("absolute", "relative"):
            for snr in sorted(df.snr.dropna().unique()):
                cv = cell_values(df, kind, mode, snr)
                cv["noise"], cv["mode"], cv["snr"] = kind, mode, snr
                allc.append(cv)
    cv = cell_values(df, None, None, None); cv["noise"], cv["mode"], cv["snr"] = "clean", "clean", np.nan
    allc.append(cv)
    summ = pd.concat(allc, ignore_index=True)
    summ.to_csv(os.path.join(a.out, "summary.csv"), index=False)

    # figures
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 8, "font.family": "serif", "pdf.fonttype": 42})
    snrs = sorted(df[(df.noise == "white") & (df["mode"] == "absolute")].snr.dropna().unique())
    ncol_f = min(3, len(groups)); nrow_f = int(np.ceil(len(groups) / ncol_f))
    fig, axes = plt.subplots(nrow_f, ncol_f, figsize=(7.0, 2.0 * nrow_f + 0.7), squeeze=False)
    for ax in axes.flat[len(groups):]:
        ax.set_visible(False)
    for ax, g in zip(axes.flat, groups):
        for m, lab in MODELS:
            ys = []
            for s in snrs:
                r = summ[(summ.group == g) & (summ.model == m) & (summ.noise == "white") &
                         (summ["mode"] == "absolute") & (summ.snr == s)]
                ys.append(r["mean"].iloc[0] if len(r) else np.nan)
            if np.all(np.isnan(ys)):
                continue
            st = dict(lw=1.6, color="k") if m == "phyq_nomed" else dict(lw=0.8)
            ax.plot(snrs, ys, marker="o", ms=2.5, label=lab, **st)
        ax.set_title(g); ax.grid(alpha=0.3)
    for ax in axes[-1]:
        ax.set_xlabel("SNR (dB)")
    for row in axes:
        row[0].set_ylabel("Accuracy (%)")
    h, lab = axes[0][0].get_legend_handles_labels()
    fig.legend(h, lab, loc="lower center", ncol=min(5, len(lab)), frameon=False, bbox_to_anchor=(0.5, 0.0))
    fig.tight_layout(rect=(0, 0.09, 1, 1))
    fig.savefig(os.path.join(a.out, "Figure_5_snr_curves.pdf")); plt.close(fig)

    fig, ax = plt.subplots(figsize=(7, 2.8))
    present = [m for m, _ in MODELS if m in set(df.model)]
    w = 0.8 / max(1, len(present))
    for i, m in enumerate(present):
        ys = []
        for g in groups:
            r = summ[(summ.group == g) & (summ.model == m) & (summ.noise == "impulsive") &
                     (summ["mode"] == "absolute") & (summ.snr == -6)]
            ys.append(r["mean"].iloc[0] if len(r) else np.nan)
        ax.bar(np.arange(len(groups)) + (i - len(present) / 2 + 0.5) * w, ys, w, label=labels[m],
               color="k" if m == "phyq_nomed" else None)
    ax.set_xticks(np.arange(len(groups)), groups); ax.set_ylabel("Accuracy (%)\nimpulsive, -6 dB")
    ax.set_ylim(0, 105); ax.grid(axis="y", alpha=0.3)
    ax.legend(ncol=5, frameon=False, fontsize=6.5, loc="lower center", bbox_to_anchor=(0.5, 1.0))
    fig.tight_layout(); fig.savefig(os.path.join(a.out, "Figure_6_impulsive.pdf")); plt.close(fig)
    print(f"-> {a.out}")
    for f in sorted(os.listdir(a.out)):
        print("  ", f)


if __name__ == "__main__":
    main()
