"""Fault-line prominence above off-frequency controls, separately for outer-race (BPFO), inner-race (BPFI)
and ball (BSF) classes of CWRU (advisor comment 5). Reads results/interp/_analysis/*.npz written by
scripts/interpret.py and uses the metric of Fig. 10e (scripts/pro_figures._excess_prom), restricted to the
classes of one fault type. Output: results/interp/_analysis/fault_types.json and a LaTeX table."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pro_figures import _excess_prom  # noqa: E402

TYPES = {"BPFO (outer race)": "OR", "BPFI (inner race)": "IR", "BSF (ball)": "B"}
REPS = [("input", "quad", "Raw input"), ("input_env", "quad", "Squared Hilbert envelope (analyst)"),
        ("input_tkeo", "quad", "Teager--Kaiser energy (analyst)"),
        ("stem_pre", "lin", "Linear stem, before activation"), ("stem_post", "lin", "Linear stem, after BN + Meta-ACON"),
        ("stem_pre", "quad", "Quadratic stem, before BN"), ("product", "quad", "\\quad bilinear term"),
        ("power", "quad", "\\quad power term"), ("stem_post", "quad", "Quadratic stem, after BN + Meta-ACON")]


def subset(z, prefix):
    names = [str(c) for c in z["class_names"]]
    keep = np.array([n.startswith(prefix) for n in names])
    if prefix == "B":
        keep = np.array([n.startswith("B") for n in names])
    ff = z["fault_freq_per_class"].astype(float).copy()
    ff[~keep] = np.nan
    zz = dict(z)
    zz["fault_freq_per_class"] = ff
    return zz


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--analysis", default="results/interp/_analysis")
    ap.add_argument("--cond", default="clean")
    ap.add_argument("--tex", default="results/interp/_analysis/tab_fault_types.tex")
    a = ap.parse_args()
    root = Path(a.analysis)
    sets = {}
    for p in sorted(root.glob("cwru__*.npz")):
        _, var, tag = p.stem.split("__")
        sets.setdefault("lin" if tag.endswith("noquad") else "quad", {})[var] = dict(np.load(p, allow_pickle=False))
    out = {}
    for rep, net, label in REPS:
        row = {}
        for tname, pre in list(TYPES.items()) + [("all faults", None)]:
            vals = []
            for var, z in sorted(sets.get(net, {}).items()):
                zz = subset(z, pre) if pre else z
                vals.append(_excess_prom(zz, rep, a.cond)[2])
            row[tname] = {"mean": float(np.nanmean(vals)), "min": float(np.nanmin(vals)), "max": float(np.nanmax(vals))}
        out[f"{net}:{rep}"] = {"label": label, **row}
    (root / f"fault_types_{a.cond}.json").write_text(json.dumps(out, indent=1))
    cols = list(TYPES) + ["all faults"]
    lines = ["% generated by scripts/interp_fault_types.py", "\\begin{tabular}{l" + "r" * len(cols) + "}", "\\toprule",
             "Feature map & " + " & ".join(c.split(" ")[0] if c != "all faults" else "All" for c in cols) + " \\\\",
             "\\midrule"]
    for k, v in out.items():
        lines.append(v["label"] + " & " + " & ".join(f"{v[c]['mean']:.1f}" for c in cols) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    Path(a.tex).write_text("\n".join(lines) + "\n")
    for k, v in out.items():
        print(f"{v['label'][:40]:40s}", "  ".join(f"{c.split(' ')[0]} {v[c]['mean']:5.1f} [{v[c]['min']:5.1f},{v[c]['max']:5.1f}]" for c in cols))


if __name__ == "__main__":
    main()
