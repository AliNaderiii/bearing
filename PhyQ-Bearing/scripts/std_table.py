"""Supplementary table: mean +- standard deviation over seeds for every model, task and main test condition
(advisor comment 9). Reads tables/summary.csv written by scripts/paper_assets.py (mean over the tasks of a
group per seed, then mean / s.d. over seeds) and writes tables/tab_std.tex."""
from __future__ import annotations

import argparse
from decimal import ROUND_HALF_UP, Decimal

import pandas as pd

MODELS = [("phyq_nomed", "PhyQ-TransNet"), ("phyq_nomed_noquad", "Linear twin"), ("cnn_transformer", "CNN--Transformer"),
          ("drsn", "DRSN-CW"), ("qcnn", "QCNN"), ("wdcnn", "WDCNN"), ("stats_mlp", "Statistics MLP"),
          ("classbd", "ClassBD"), ("kurtogram_ses", "Fast Kurtogram + SES")]
GROUPS = ["CWRU", "IMS", "NREL", "SDUST", "PU 5-fold", "PU art2real"]
CONDS = [("clean", None, "Clean"), ("white", -6.0, "White, $-6$~dB"), ("white", -10.0, "White, $-10$~dB"),
         ("pink", -6.0, "Pink, $-6$~dB"), ("impulsive", -6.0, "Impulsive, $-6$~dB")]


def r1(x):
    return str(Decimal(str(x)).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", default="tables/summary.csv")
    ap.add_argument("--out", default="tables/tab_std.tex")
    a = ap.parse_args()
    d = pd.read_csv(a.summary)
    L = ["% generated by scripts/std_table.py from summary.csv (mean over tasks per seed, then mean / s.d. over seeds)",
         "\\begin{table}[p]",
         "\\caption{Test accuracy (\\%, absolute SNR) as mean $\\pm$ standard deviation over seeds (CWRU: mean of the four "
         "load tasks per seed; PU 5-fold: mean of the five folds per seed, two seeds; all other tasks three seeds). "
         "Non-finite outputs are counted as errors.}\\label{tab:std}",
         "\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}",
         "\\begin{tabular}{l" + "r" * len(GROUPS) + "}", "\\toprule",
         "Model & " + " & ".join(GROUPS) + " \\\\"]
    for noise, snr, label in CONDS:
        L += ["\\midrule", f"\\multicolumn{{{len(GROUPS) + 1}}}{{l}}{{\\emph{{{label}}}}} \\\\"]
        for tag, name in MODELS:
            cells = []
            for g in GROUPS:
                q = d[(d.group == g) & (d.model == tag) & (d.noise == noise)]
                q = q[q["mode"] == "clean"] if snr is None else q[(q["mode"] == "absolute") & (q.snr == snr)]
                if len(q) != 1:
                    cells.append("--")
                    continue
                m, s = float(q["mean"].iloc[0]), float(q["std"].iloc[0])
                cells.append(f"{r1(m)} $\\pm$ {r1(s if s == s else 0.0)}")
            L.append(name + " & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    with open(a.out, "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
