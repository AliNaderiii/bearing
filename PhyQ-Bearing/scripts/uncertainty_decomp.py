"""Seed-ensemble decomposition of predictive uncertainty (re-review, advisor comment 8).

For every task, model and test condition the softmax outputs of the independently trained seeds (identical test
windows and identical, deterministic noise realisations) are combined into a deep ensemble:
    total     H[ mean_s p_s ]                (predictive entropy of the ensemble)
    aleatoric mean_s H[ p_s ]                (expected entropy of the members)
    epistemic total - aleatoric              (mutual information between prediction and seed / weights)
All entropies are divided by log K (range 0..1). Windows for which any member produced a non-finite output are
excluded from the entropies and reported as a share. Also reported: ensemble and mean member accuracy, and the
AUROC with which each uncertainty separates the ensemble's errors from its correct predictions.

Input: results/<suite>/<dataset>/<variant>/<model>/seed*/test_probs.npz (written by phyq/runner.py).
Output: <out>/uncertainty.csv and <out>/tab_uncertainty.tex.  Ensembles of 2-3 members give coarse
mutual-information estimates; the script reports them as such.
"""
from __future__ import annotations

import argparse
import glob
import os
from decimal import ROUND_HALF_UP, Decimal

import numpy as np
import pandas as pd

TASKS = [("CWRU", "main_tuned/cwru/within_*HP"), ("IMS", "main_tuned/ims/chrono"), ("NREL", "main_tuned/nrel/expwise"),
         ("SDUST", "main_tuned/sdust/chrono"), ("PU 5-fold", "main_benchmark/pu/fold*"),
         ("PU art2real", "main_benchmark/pu/art2real")]
MODELS = [("phyq_nomed", "PhyQ-TransNet"), ("phyq_nomed_noquad", "Linear twin"), ("classbd", "ClassBD"),
          ("wdcnn", "WDCNN")]
CONDS = [("clean", "Clean"), ("white__absolute__-6", "W $-6$"), ("white__absolute__-10", "W $-10$"),
         ("pink__absolute__-6", "P $-6$"), ("impulsive__absolute__-6", "I $-6$")]


def _ent(p):
    return -(p * np.log(np.clip(p, 1e-12, 1.0))).sum(-1) / np.log(p.shape[-1])


def _auroc(score, err):
    err = err.astype(bool)
    if err.all() or (~err).all():
        return np.nan
    r = pd.Series(score).rank().to_numpy()
    n1 = err.sum()
    return float((r[err].sum() - n1 * (n1 + 1) / 2) / (n1 * (~err).sum()))


def decompose(files, key):
    zs = [np.load(f) for f in files]
    if any(key not in z.files for z in zs):
        return None
    y = zs[0]["y"]
    if any(z["y"].shape != y.shape or (z["y"] != y).any() for z in zs):
        raise ValueError(f"test windows differ between seeds: {files}")
    P = np.stack([z[key].astype(np.float64) for z in zs])          # (S, N, K)
    fin = np.isfinite(P).all(axis=(0, 2))
    member_acc = float(np.mean([(np.where(np.isfinite(p).all(1), p.argmax(1), -1) == y).mean() for p in P]))
    P, yy = P[:, fin], y[fin]
    pm = P.mean(0)
    tot, ale = _ent(pm), _ent(P).mean(0)
    epi = np.clip(tot - ale, 0.0, None)
    err = pm.argmax(1) != yy
    return {"n_seeds": len(files), "n": int(len(y)), "nonfinite": float(1 - fin.mean()),
            "ens_acc": float((~err).sum() / len(y)), "member_acc": member_acc,
            "total": float(tot.mean()), "aleatoric": float(ale.mean()), "epistemic": float(epi.mean()),
            "epi_share": float(epi.sum() / max(tot.sum(), 1e-12)),
            "auroc_total": _auroc(tot, err), "auroc_epistemic": _auroc(epi, err)}


def r(x, nd=1):
    if x != x:
        return "--"
    return str(Decimal(str(x)).quantize(Decimal(10) ** -nd, rounding=ROUND_HALF_UP))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--out", default="results/uncertainty")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    rows = []
    for gname, pat in TASKS:
        for tag, _ in MODELS:
            for var_dir in sorted(glob.glob(os.path.join(a.results, pat))):
                files = sorted(glob.glob(os.path.join(var_dir, tag, "seed*", "test_probs.npz")))
                if len(files) < 2:
                    continue
                for key, _ in CONDS:
                    d = decompose(files, key)
                    if d:
                        rows.append(dict(group=gname, variant=os.path.basename(var_dir), model=tag, cond=key, **d))
    df = pd.DataFrame(rows)
    df.to_csv(os.path.join(a.out, "uncertainty.csv"), index=False)
    g = df.groupby(["group", "model", "cond"]).mean(numeric_only=True).reset_index()
    g.to_csv(os.path.join(a.out, "uncertainty_by_group.csv"), index=False)
    # LaTeX: epistemic share of the total entropy (%) and AUROC of the total entropy for error detection
    L = ["% generated by scripts/uncertainty_decomp.py",
         "\\begin{table}[p]",
         "\\caption{Seed-ensemble decomposition of predictive uncertainty (3 seeds; PU 5-fold: 2). Each cell: "
         "ensemble accuracy (\\%) / epistemic share of the predictive entropy (\\%, mutual information over "
         "total entropy) / AUROC of the predictive entropy for detecting the ensemble's errors. Absolute SNR in dB; "
         "windows with non-finite outputs excluded from the entropies (counted as errors in the accuracy).}"
         "\\label{tab:uncert}",
         "\\centering\\scriptsize\\setlength{\\tabcolsep}{2pt}",
         "\\resizebox{\\textwidth}{!}{%",
         "\\begin{tabular}{ll" + "l" * len(TASKS) + "}", "\\toprule",
         "Condition & Model & " + " & ".join(t for t, _ in TASKS) + " \\\\"]
    for key, clab in CONDS:
        L.append("\\midrule")
        for i, (tag, name) in enumerate(MODELS):
            cells = []
            for t, _ in TASKS:
                q = g[(g.group == t) & (g.model == tag) & (g.cond == key)]
                cells.append("--" if q.empty else
                             f"{r(100 * q.ens_acc.iloc[0])} / {r(100 * q.epi_share.iloc[0], 0)} / {r(q.auroc_total.iloc[0], 2)}")
            L.append((clab if i == 0 else "") + " & " + name + " & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
    with open(os.path.join(a.out, "tab_uncertainty.tex"), "w") as f:
        f.write("\n".join(L) + "\n")
    print(g.to_string(max_rows=400))


if __name__ == "__main__":
    main()
